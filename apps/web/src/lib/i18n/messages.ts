export const resolveLocaleFromDevice = (
  deviceLanguage: string | undefined,
): ResolvedLocale => {
  const normalized = (deviceLanguage ?? "").toLowerCase();
  if (normalized.startsWith("ar")) return "ar";
  if (normalized.startsWith("fr")) return "fr";
  return "en";
};
